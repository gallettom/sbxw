#!/usr/bin/env python3
"""The big fixture of the performance runs (generated on each run, about 5 MB):
the realistic sizes the person's own daemon has, built from the existing
fixtures so the routes answer as they do.

- 11 sandboxes with their sessions, threads, plans (fixtures/shell/statusbar-many.json, one more sandbox);
- 200 commits on web-app (and the other repos' few), each with its detail: 12 files of ~40 diff lines;
- a 3,000-entry folder in the Files explorer (files/standin.json's workspace, `/Users/me/web/big`);
- 113 pending network requests over the sandboxes;
- the worktrees of fixtures/worktrees/standin.json.

    python3 desktop/scripts/perf-fixture.py > big.json   (about 5 MB: generated, not kept in git)
"""
import copy, hashlib, json, os, sys

here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fixtures")
load = lambda p: json.load(open(os.path.join(here, p)))

base = load("shell/statusbar-many.json")
out = {"about": "Generated by desktop/scripts/perf-fixture.py: realistic sizes for the performance runs (PERF.md).", "daemon": copy.deepcopy(base["daemon"]), "app": base.get("app", {})}
d = out["daemon"]
# The 11th: web-app, whose workspace the Files and Commits data are about.
fs = load("files/standin.json")["daemon"]
d["sandboxes"].append(copy.deepcopy(next(x for x in fs["sandboxes"] if x["name"] == "web-app")))
names = [s["name"] for s in d["sandboxes"]]

# Commits: 200 on web-app, 20 on three others, each with its detail.
commits, details = {}, {}
patch_lines = ["@@ -%d,7 +%d,9 @@ export function Thing() {" , "   const a = useState(null);", "-  const label = 'old';", "+  const label = isMobile ? 'new' : 'newer';", "+  if (x) { return null; }", "   return (", "     <Form onSubmit={submit}>"]
for sb, n in [("web-app", 200)] + [(s, 20) for s in names[1:4]]:
    rows = []
    for i in range(n):
        h = hashlib.sha1(f"{sb}-{i}".encode()).hexdigest()
        row = {"hash": h, "short": h[:7], "author": ["Ana Ruiz", "Lee Park", "Sam Diallo"][i % 3], "at": 1794896400 - i * 3600,
               "subject": f"Change {i}: tidy the checkout's payment step and its copy", "body": "A body line.\nA second line, a bit longer than the first one.",
               "branch": "main" if i % 4 else f"sbxw/t{i % 7}", "thread": None if i % 4 else f"t{i % 7}", "merged": i % 4 != 0, "files": 12, "repo": ""}
        rows.append(row)
        files = []
        for f in range(12):
            body = "\n".join(l % (10 + f, 10 + f) if "%d" in l else l for l in patch_lines * 6)
            files.append({"path": f"src/area{f}/File{f}.tsx", "added": 18, "removed": 6, "binary": False, "truncated": False,
                          "patch": f"diff --git a/src/area{f}/File{f}.tsx b/src/area{f}/File{f}.tsx\n--- a/x\n+++ b/x\n" + body + "\n"})
        details[h] = dict(row, files=files)
    commits[sb] = rows
d["commits"] = commits
d["commit_details"] = details

# Files: the explorer's standin data, plus a 3,000-entry folder.
for k in ["artifacts", "files_dir", "files_recent", "codemap", "files_tree", "files_content"]:
    d[k] = copy.deepcopy(fs[k])
big = {"path": "/Users/me/web/big", "parent": "/Users/me/web",
       "entries": [{"name": f"module_{i:04d}.{['ts', 'md', 'json'][i % 3]}", "kind": "file", "link": False, "size": 1000 + i, "modified": 1794199100 - i} for i in range(3000)]}
for k in [k for k in fs["files_dir"] if k not in ("path", "parent", "entries")]:
    big[k] = fs["files_dir"][k]
d["files_tree"]["/Users/me/web/big"] = big
d["files_tree"]["/Users/me/web"]["entries"].append({"name": "big", "kind": "dir", "link": False, "size": 4096, "modified": 1794199100})

# 113 pending network requests.
reqs = []
for i in range(113):
    sb = names[i % len(names)]
    reqs.append({"id": f"network:p{i}", "kind": "network", "sandbox": sb, "title": f"host{i % 37}.example.com:443", "detail": "HTTPS through sbx's proxy\nNo rule allows this host",
                 "created_at": "2026-11-15T21:58:00Z", "options": [{"id": "allow", "label": "Allow always"}, {"id": "allow-once", "label": "Allow once"}, {"id": "deny", "label": "Deny"}]})
d["approvals"] = {"ok": True, "approvals": reqs}

wt = load("worktrees/standin.json")["daemon"]
d["worktrees_of"] = wt["worktrees_of"]
json.dump(out, sys.stdout)
