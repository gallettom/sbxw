//! Embeds the bundled kits: every file under `assets/<kit>/` that sbx reads
//! (`spec.yaml` and the `files/` tree its `build:` copies), with its mode, as
//! `KITS` in `$OUT_DIR/bundled_kits.rs`. A kit is a directory now (kit spec
//! v3: image content beside the descriptor), not one spec string.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The kits that ship in the binary, as `sbxw:<name>`. `base` is sbxw's own,
/// applied to every sandbox; the rest are `sbxw_core::kits::BUNDLED`.
const KITS: [&str; 9] = ["base", "codemap", "agent-skills", "md-to-pdf-tools", "retro", "k8s-tools", "git-identity", "ssh-agent", "terminal-mac"];

fn main() {
    let assets = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets").canonicalize().expect("assets/");
    let mut out = String::from("/// `(kit, [(relative path, mode, bytes)])`, generated by build.rs.\npub const KITS: &[(&str, &[(&str, u32, &[u8])])] = &[\n");
    for kit in KITS {
        let dir = assets.join(kit);
        println!("cargo:rerun-if-changed={}", dir.display());
        let mut files = vec![dir.join("spec.yaml")];
        walk(&dir.join("files"), &mut files);
        files.sort();
        writeln!(out, "    ({kit:?}, &[").unwrap();
        for f in files {
            let rel = f.strip_prefix(&dir).unwrap().to_string_lossy().replace('\\', "/");
            let mode = if executable(&f) { 0o755 } else { 0o644 };
            writeln!(out, "        ({rel:?}, 0o{mode:o}, include_bytes!({:?})),", f.display().to_string()).unwrap();
        }
        out.push_str("    ]),\n");
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("bundled_kits.rs");
    std::fs::write(dest, out).unwrap();
}

fn walk(dir: &Path, acc: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    println!("cargo:rerun-if-changed={}", dir.display());
    for e in entries.flatten() {
        let p = e.path();
        let Ok(t) = e.file_type() else { continue };
        if t.is_dir() {
            walk(&p, acc);
        } else if t.is_file() {
            println!("cargo:rerun-if-changed={}", p.display());
            acc.push(p);
        }
    }
}

#[cfg(unix)]
fn executable(p: &Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    std::fs::metadata(p).is_ok_and(|m| m.permissions().mode() & 0o111 != 0)
}

#[cfg(not(unix))]
fn executable(p: &Path) -> bool {
    // Git keeps the bit; a Windows checkout does not. The scripts the kits run
    // are the ones under a bin/ directory or ending in .sh / .mjs.
    let s = p.to_string_lossy();
    s.contains("/bin/") || s.ends_with(".sh") || s.ends_with(".mjs")
}
